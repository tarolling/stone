#!/usr/bin/env python3
"""Writes src/stdlib/gui_keysyms.stn, the keysym table of the `gui` module, from xorgproto's
keysymdef.h.

Each keysym's name, value, and Unicode code point (0 for a key that types nothing, such as
BackSpace) comes from a line such as

    #define XK_Cyrillic_ef  0x06c6  /* U+0444 CYRILLIC SMALL LETTER EF */

where the comment may also be written `/*(U+...)*/` (an approximate character) or `/*<U+...>*/`
(a keypad key that types it).

Usage: python3 scripts/gen-keysyms.py [/usr/include/X11/keysymdef.h]
"""

import re
import sys
from pathlib import Path

DEFINE = re.compile(r"^#define XK_(\w+)\s+0x([0-9a-fA-F]+)\s*(?:/\*\s*[(<]?U\+([0-9A-Fa-f]+))?")
WIDTH = 100


def lines_of(var, words, indent="    "):
    """Splits `words` into `var.append("...")` statements of words separated by spaces, each of
    which fits in WIDTH columns."""
    out = []
    row = []
    for word in words:
        candidate = row + [word]
        if row and len(f'{indent}{var}.append("{" ".join(candidate)}")') > WIDTH:
            out.append(f'{indent}{var}.append("{" ".join(row)}")')
            row = [word]
        else:
            row = candidate
    if row:
        out.append(f'{indent}{var}.append("{" ".join(row)}")')
    return out


def main():
    source = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/include/X11/keysymdef.h")
    text = source.read_text()
    notice = text[text.index("/*") + 2 : text.index("*/")].strip("*\n ")
    entries = []
    for line in text.splitlines():
        found = DEFINE.match(line)
        if found:
            name, value, code = found.groups()
            entries.append((name, int(value, 16), int(code, 16) if code else 0))
    out = [
        "// The keysyms of X11, generated by scripts/gen-keysyms.py from xorgproto's keysymdef.h,",
        "// which carries this notice:",
        "//",
    ]
    out += [f"// {line}".rstrip() for line in notice.splitlines()]
    out += [
        "",
        "// Every keysym's name, value, and the Unicode character it types (0 for none), in the",
        "// order keysymdef.h lists them. They are kept as text, which costs a program nothing until",
        "// it reads them, where list literals would be code.",
        "pub fn table() -> tuple[list[str], list[int], list[int]]:",
        "    names = []",
        "    values = []",
        "    codes = []",
    ]
    out += lines_of("names", [name for name, _, _ in entries])
    out += lines_of("values", [str(value) for _, value, _ in entries])
    out += lines_of("codes", [str(code) for _, _, code in entries])
    out += [
        '    ret (" ".join(names).split(" "), numbers(values), numbers(codes))',
        "",
        "// The numbers the words of `lines` write.",
        "fn numbers(lines: list[str]) -> list[int]:",
        "    found = []",
        '    for word in " ".join(lines).split(" "):',
        "        found.append(int(word).unwrap_or(0))",
        "    ret found",
    ]
    target = Path(__file__).resolve().parent.parent / "src" / "stdlib" / "gui_keysyms.stn"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {len(entries)} keysyms to {target}")


if __name__ == "__main__":
    main()
