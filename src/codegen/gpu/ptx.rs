    #[test]
    fn an_int_kernel_wraps_and_moves_eight_bytes_at_a_time() {
        // -(a - b * -3)
        let source = ir::Kernel::Neg(Box::new(ir::Kernel::Binary(
            BinOp::Sub,
            list(1),
            Box::new(ir::Kernel::Binary(
                BinOp::Mul,
                list(2),
                Box::new(ir::Kernel::Number(Operand::Imm(-3))),
            )),
        )));
        let text = module(&[kernel(source, false)], sm_75()).unwrap();
        for wanted in [
            "\tmov.b64 \t%rd5, -3;\n",
            "\tld.global.u64 \t%rd",
            "\tmul.lo.s64 \t%rd",
            "\tsub.s64 \t%rd",
            "\tneg.s64 \t%rd",
            "\tst.global.u64 \t[%rd",
        ] {
            assert!(text.contains(wanted), "{wanted:?} in {text}");
        }
        assert!(!text.contains("f64"), "{text}");
    }

    #[test]
    fn floats_differ_only_when_neither_is_nan_or_one_is() {
        use crate::codegen::gpu::ir::{Block, Kernel};
        let kernel = Kernel {
            name: "k".to_string(),
            params: vec![Ty::F64],
            types: vec![Ty::F64, Ty::Pred],
            blocks: vec![Block {
                insts: vec![
                    Inst::Param {
                        dst: Value(0),
                        index: 0,
                    },
                    Inst::Cmp {
                        cond: Cond::Ne,
                        dst: Value(1),
                        lhs: Value(0),
                        rhs: Value(0),
                    },
                ],
                term: Terminator::Ret,
            }],
            sites: vec![],
        };
        let text = module(&[kernel], sm_75()).unwrap();
        assert!(
            text.contains("\tld.param.f64 \t%fd1, [k_param_0];\n"),
            "{text}"
        );
        assert!(
            text.contains("\tsetp.neu.f64 \t%p1, %fd1, %fd1;\n"),
            "{text}"
        );
    }

    #[test]
    fn a_module_declares_the_ptx_its_gpu_needs() {
        for (device, header) in [
            ("sm_75", ".version 6.3\n.target sm_75\n"),
            ("sm_90a", ".version 8.0\n.target sm_90a\n"),
            ("sm_120", ".version 8.7\n.target sm_120\n"),
        ] {
            let text = module(&[], device.parse().unwrap()).unwrap();
            assert!(text.contains(header), "{text}");
            assert!(text.ends_with(".address_size 64\n"), "{text}");
        }
        let amd = module(&[], "gfx1100".parse().unwrap());
        assert_eq!(
            amd,
            Err("AMD GPUs (gfx1100) are not supported yet".to_string())
        );
    }
